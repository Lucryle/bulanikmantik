"""Fair tuning of every controller with the SAME budget (assumption A21).

Protocol
  * random search, ``--budget`` candidates per controller (default 60);
    candidate 0 is always the hand-written config,
  * every candidate is run on scenarios A, B and C with the 10 TUNING seeds
    (1000–1009, configs/default.yaml). Test seeds (0–29) are never used here,
  * objective = mean UAV–target distance over the whole trial (lower is
    better; it rewards fast capture AND small tracking error, and it is
    defined even when the target is never captured),
  * the best candidate is written to configs/controllers/<name>_tuned.yaml.

Usage:
  python experiments/tune.py                       # all controllers
  python experiments/tune.py --controllers pid it2_paper
Output: configs/controllers/<name>_tuned.yaml, results/tables/tuning_<name>.csv
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import yaml  # noqa: E402

from src.config import CONFIGS, load_controller  # noqa: E402
from src.experiment import TABLES, Job, run_jobs, tuning_seeds  # noqa: E402

SCENARIOS = ["A", "B", "C"]

# Search space per controller: parameter -> (low, high, scale).
# Scales: "log" = log-uniform, "lin" = uniform.
SPACES = {
    "pid": {"kp": (0.3, 20.0, "log"), "ki": (0.0, 3.0, "lin"), "kd": (0.0, 1.5, "lin")},
    "it2_paper": {"input_gain": (0.5, 20.0, "log"), "output_gain": (0.5, 3.0, "lin")},
    "it2_pd": {"input_gain": (0.5, 20.0, "log"), "de_gain": (0.02, 1.0, "log"),
               "output_gain": (0.5, 3.0, "lin")},
}


def sample(space: dict, rng: np.random.Generator) -> dict:
    out = {}
    for name, (lo, hi, scale) in space.items():
        if scale == "log":
            out[name] = float(np.exp(rng.uniform(np.log(lo), np.log(hi))))
        else:
            out[name] = float(rng.uniform(lo, hi))
    return out


def tune(name: str, budget: int, seed: int = 0) -> dict:
    base = load_controller(name)
    space = SPACES[name]
    rng = np.random.default_rng(seed)
    candidates = [{k: base[k] for k in space}] + [sample(space, rng) for _ in range(budget - 1)]

    jobs = [Job(sc, {**base, **cand}, s, tags={"candidate": i})
            for i, cand in enumerate(candidates) for sc in SCENARIOS for s in tuning_seeds()]
    df = run_jobs(jobs, desc=f"tuning {name}")
    score = df.groupby("candidate")["mean_error_all"].mean()
    capture = df.groupby("candidate")["captured"].mean()

    table = [{"candidate": i, **{k: round(v, 4) for k, v in cand.items()},
              "objective (m)": round(float(score[i]), 4),
              "capture rate (%)": round(100 * float(capture[i]), 1)}
             for i, cand in enumerate(candidates)]
    TABLES.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(table).sort_values("objective (m)").to_csv(TABLES / f"tuning_{name}.csv", index=False)

    best = int(score.idxmin())
    tuned = {**base, **{k: round(v, 4) for k, v in candidates[best].items()}}
    header = (f"# GENERATED by experiments/tune.py — do not edit by hand.\n"
              f"# Base config: {name}.yaml. Random search, budget {budget}, scenarios "
              f"{'/'.join(SCENARIOS)}, tuning seeds {tuning_seeds()[0]}–{tuning_seeds()[-1]}.\n"
              f"# Best candidate #{best}: objective {score[best]:.3f} m "
              f"(hand-written config: {score[0]:.3f} m).\n")
    path = CONFIGS / "controllers" / f"{name}_tuned.yaml"
    path.write_text(header + yaml.safe_dump(tuned, sort_keys=False), encoding="utf-8")
    print(f"{name}: best #{best} {candidates[best]} -> {score[best]:.3f} m (base {score[0]:.3f} m)")
    return tuned


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--controllers", nargs="+", default=["pid", "it2_paper", "it2_pd"], choices=list(SPACES))
    ap.add_argument("--budget", type=int, default=60)
    args = ap.parse_args()
    for name in args.controllers:
        tune(name, args.budget)


if __name__ == "__main__":
    main()
